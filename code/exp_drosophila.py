"""Drosophila larvae flight-memory analysis (Sims et al. 2019, eLife 8:e50316; Zenodo 4996872, CC0).

Question: is the intrinsic walk generated by the ventral nerve cord CPG a renewal process (i.i.d. flights),
or does the flight sequence carry memory? Does memory survive synaptic silencing or ablation of brain lobes
and sensory neurons?

Per-track pipeline: (X, Y) in mm at 2 Hz → rectangular corridor segmentation (half-width eps) →
collinear merging (|Δθ| < 20°) → flight lengths ℓ_t.
Per condition: causal MaxEnt model with individual fields h_i (fixed effects) and shared couplings J_τ.
Null controls: (i) within-larva flight permutation; (ii) trajectory chunk-shuffle (pipeline null:
rebuilding tracks from shuffled flight chunks with empirical turning angles and re-segmenting).
"""
