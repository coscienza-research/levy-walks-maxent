def load_key():
    key = pd.read_excel(os.path.join(D, "Supplementary_File_3.xlsx"), sheet_name="Analysis")
    key = key[["Treatment", "Trial", "Track"]].dropna(subset=["Track"])
    norm = lambda s: re.sub(r"[^a-z0-9()]", "", s.lower().replace(".nc", "").replace(".csv", ""))
    files = {norm(os.path.basename(f)): os.path.basename(f) for f in glob.glob(os.path.join(D, "*.csv"))}
    key["csv"] = key.Track.apply(norm).map(files)
    key["Treatment"] = key.Treatment.replace({"New BLsens-rprhid_control": "New Blsens-rprhid_control"})
    return key.dropna(subset=["csv"]).reset_index(drop=True)


def track_flights(xy, eps, theta_c=np.deg2rad(20)):
    lens, st = segment_flights(xy, eps)
    lm, sm = merge_collinear(xy, st, theta_c)
    return lm, sm


def turning_angles(xy, starts):
    ends = list(starts[1:]) + [len(xy) - 1]
    v = np.array([xy[e] - xy[s] for s, e in zip(starts, ends)])
    a = np.arctan2(v[:, 1], v[:, 0])
    return np.angle(np.exp(1j * np.diff(a)))


def _seg_one(args):
    f, eps = args
    xy = pd.read_csv(os.path.join(D, f))[["X", "Y"]].to_numpy()
    lm, sm = track_flights(xy, eps)
    return f, lm, sm, len(xy)


def get_flights(eps):
    """Segment all larval tracks (cached on disk)."""
    path = os.path.join(CACHE, f"dros_flights_eps{eps:g}.npz")
    key = load_key()
    if os.path.exists(path):
        z = np.load(path, allow_pickle=True)
        return key, z["flights"].item(), z["starts"].item(), z["nfr"].item()
    flights, starts, nfr = {}, {}, {}
    with ProcessPoolExecutor(6) as ex:
        for f, lm, sm, n in ex.map(_seg_one, [(f, eps) for f in key.csv]):
            flights[f], starts[f], nfr[f] = lm, sm, n
    np.savez(path, flights=flights, starts=starts, nfr=nfr)
    return key, flights, starts, nfr


def chunk_shuffle(xy, starts, rng):
    """Pipeline null: shuffle the order of flight chunks (with their sub-sampled points)
    and reconnect them using turning angles drawn from the empirical distribution."""
    ends = list(starts[1:]) + [len(xy) - 1]
    chunks = [xy[s:e + 1] - xy[s] for s, e in zip(starts, ends)]
    turns = turning_angles(xy, starts)
    order = rng.permutation(len(chunks))
    out = [np.zeros((1, 2))]
    heading = 0.0
    for k, i in enumerate(order):
        c = chunks[i]
        v = c[-1]
        a0 = np.arctan2(v[1], v[0])
        heading = heading + (rng.choice(turns) if (k > 0 and len(turns)) else 0.0)
        R = np.array([[np.cos(heading - a0), -np.sin(heading - a0)], [np.sin(heading - a0), np.cos(heading - a0)]])
        out.append(out[-1][-1] + c[1:] @ R.T)
    return np.vstack(out)


def to_x_list(seqs, lmin, lmax):
    L = float(np.log(lmax / lmin))
    xs = [np.clip(np.log(np.asarray(s) / lmin), 0, L) for s in seqs]
    clip = float(np.mean(np.concatenate(seqs) < lmin))
    return xs, L, clip


def analyze_condition(task):
    cond, eps, lmin, Kmax, n_surr, n_pipe, do_hmm = task
    key, flights, starts, _ = get_flights(eps)
    rng = np.random.default_rng(zlib.crc32(repr((cond, eps, lmin)).encode()))
    files = list(key.csv[key.Treatment == cond])
    seqs = [flights[f] for f in files if len(flights[f]) > Kmax + 10]
    files = [f for f in files if len(flights[f]) > Kmax + 10]
    allv = np.concatenate(seqs)
    lmax = allv.max() * 1.001
    xs, L, clip = to_x_list(seqs, lmin, lmax)
    out = dict(cond=cond, eps=eps, lmin=lmin, lmax=float(lmax), L=L, clip=clip, n_tracks=len(xs),
               n_flights=int(sum(len(x) for x in xs)), med_len=float(np.median([len(x) for x in xs])))
    fe = scan_orders_fe(xs, L, Kmax)
    po = scan_orders(xs, L, Kmax)
    fe_ln = scan_orders_fe(xs, L, Kmax, family="lognormal")
    out["fe_bic"] = [f.bic for f in fe]; out["fe_aic"] = [f.aic for f in fe]
    out["fe_K_bic"] = select(fe, "bic")[0]; out["fe_K_aic"] = select(fe, "aic")[0]
    out["pooled_K_bic"] = select(po, "bic")[0]
    out["fe_J"] = {K: fe[K].extra["J"].tolist() for K in range(1, Kmax + 1)}
    out["fe_seJ"] = {K: fe[K].extra["se_J"].tolist() for K in range(1, Kmax + 1)}
    out["h_i"] = fe[0].extra["h_i"].tolist()
    out["mu_i"] = (1 - fe[0].extra["h_i"]).tolist()
    out["fe_ln_K_bic"] = select(fe_ln, "bic")[0]
    out["fe_ln_bic"] = [f.bic for f in fe_ln]
    out["dBIC_pl_minus_ln_K0"] = fe[0].bic - fe_ln[0].bic
    kk = out["fe_K_bic"]
    out["dBIC_pl_minus_ln_Kstar"] = fe[kk].bic - fe_ln[select(fe_ln, "bic")[0]].bic
    # null (i): permutazione entro traccia
    sJ, sK = [], []
    for _ in range(n_surr):
        xs_s = [rng.permutation(x) for x in xs]
        fs = scan_orders_fe(xs_s, L, min(Kmax, 3))
        sK.append(select(fs, "bic")[0]); sJ.append(fs[1].extra["J"][0])
    out["shuffle_K_bic"] = sK; out["shuffle_J1"] = sJ
    # null (ii): chunk shuffle della traiettoria + stessa pipeline
    pK, pJ = [], []
    for _ in range(n_pipe):
        seqs_p = []
        for f in files:
            xy = pd.read_csv(os.path.join(D, f))[["X", "Y"]].to_numpy()
            xy2 = chunk_shuffle(xy, starts[f], rng)
            lm, _ = track_flights(xy2, eps)
            if len(lm) > Kmax + 10:
                seqs_p.append(lm)
        xp, Lp, _ = to_x_list(seqs_p, lmin, max(lmax, np.concatenate(seqs_p).max() * 1.001))
        fp = scan_orders_fe(xp, Lp, min(Kmax, 3))
        pK.append(select(fp, "bic")[0]); pJ.append(fp[1].extra["J"][0])
    out["pipe_K_bic"] = pK; out["pipe_J1"] = pJ
    # confronto per-traccia: i.i.d. vs MaxEnt K=1 vs HMM a 2 stati (tutti per-traccia)
    if do_hmm:
        rows = []
        for x in xs:
            if len(x) < 60:
                continue
            f0 = scan_orders([x], L, 1)
            hm = fit_hmm([x], L, M=2, fam="pl", Kcond=1, n_starts=4, rng=rng)
            rows.append(dict(n=len(x), aic_iid=f0[0].aic, aic_me1=f0[1].aic, aic_hmm=hm["aic"],
                             bic_iid=f0[0].bic, bic_me1=f0[1].bic, bic_hmm=hm["bic"], J1=float(f0[1].J[0])))
        out["per_track"] = rows
    return out


def block_control(task):
    """Short-range memory vs slow drift: local fields h re-estimated every B flights.
    Null: within-block permutation (preserves block fields, destroys sequential memory)."""
    cond, eps, lmin, B, fam, n_surr = task
    key, flights, _, _ = get_flights(eps)
    rng = np.random.default_rng(zlib.crc32(repr(task).encode()))
    seqs = [flights[f] for f in key.csv[key.Treatment == cond] if len(flights[f]) > 16]
    lmax = np.concatenate(seqs).max() * 1.001
    xs, L, clip = to_x_list(seqs, lmin, lmax)
    fits = scan_orders_fe(xs, L, 4, family=fam, block=B)
    out = dict(cond=cond, B=B if B else 0, fam=fam, K_bic=select(fits, "bic")[0], n_fields=fits[0].extra["n_seq"],
               J1=float(fits[1].extra["J"][0]), seJ1=float(fits[1].extra["se_J"][0]),
               J_K4=fits[4].extra["J"].tolist(), seJ_K4=fits[4].extra["se_J"].tolist())
    nullJ, nullK = [], []
    for _ in range(n_surr):
        xs_s = []
        for x in xs:
            x = x.copy()
            if B:
                # permute within blocks (same partition used by design: offset Kmax=4)
                for s in range(4, len(x), B):
                    seg = x[s:s + B]
                    x[s:s + B] = rng.permutation(seg)
            else:
                x = rng.permutation(x)
            xs_s.append(x)
        fs = scan_orders_fe(xs_s, L, 4, family=fam, block=B)
        nullJ.append(float(fs[1].extra["J"][0])); nullK.append(select(fs, "bic")[0])
    out["null_J1"] = nullJ; out["null_K"] = nullK
    out["z"] = float((out["J1"] - np.mean(nullJ)) / (np.std(nullJ) + 1e-12))
    return out


def phase_index(cond, eps=0.5, lmin=1.0, arena=(240.0, 339.0)):
    """Condensation control parameter Φ_i = J_1 L / (μ_bare,i - 1) = J_1 / J_up per larva (Table I).

    J_1 from a K=1 fixed-effects fit; μ_bare,i = 1 - h'_i with h'_i = h_i - J_1 c_i the field
    after the shortest flight (x_{t-1} = 0). Thresholds: Φ = 1 (spinodal), Φ = 2 (self-dual condensation).
    Cutoff control: same fit with ℓ_max set to the side (240 mm) and diagonal (339 mm) of the arena."""
    key, flights, _, _ = get_flights(eps)
    seqs = [flights[f] for f in key.csv[key.Treatment == cond] if len(flights[f]) > 16]
    N = int(sum(len(s) for s in seqs))
    lmax_hat = np.concatenate(seqs).max() * 1.001
    out = dict(cond=cond, N=N)
    for tag, lmax in [("hat", lmax_hat)] + [(f"arena{a:g}", a) for a in arena]:
        xs, L, _ = to_x_list(seqs, lmin, lmax)
        fe = scan_orders_fe(xs, L, 1)
        J1 = float(fe[1].extra["J"][0])
        c = np.array([x.mean() for x in xs])
        mu0 = 1 - (fe[1].extra["h_i"] - J1 * c)
        ok = mu0 > 1
        phi = J1 * L / (mu0[ok] - 1)
        if tag == "hat":
            mu_iid = np.array([1 - _invert_mean(x.mean(), L) for x in xs])      # i.i.d. fit per larva
            out.update(L=L, J1=J1, mu_bare_med=float(np.median(mu0)), mu_iid_med=float(np.median(mu_iid)),
                       phase_med=float(np.median(phi)), phase_q=np.percentile(phi, [25, 75]).tolist(),
                       n_excluded=int((~ok).sum()),
                       L_extreme=float(np.log(N) / max(np.median(mu_iid) - 1, 1e-9)))  # ln N/(μ-1): Fréchet maximum
        else:
            out[f"phase_med_{tag}"] = float(np.median(phi))
    return out


